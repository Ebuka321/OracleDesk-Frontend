#!/usr/bin/env node
// Copies generated contract code out of the pinned `contracts` submodule
// (OracleDesk-SmartContract) into lib/stellar/generated/, so the build never imports
// from the submodule directly.
//
//   node scripts/sync-bindings.mjs          # write the files
//   node scripts/sync-bindings.mjs --check  # exit 1 if any file is stale
//
// After bumping the submodule (`git -C contracts checkout <commit>`), run the
// sync and commit both the submodule pointer and lib/stellar/generated/.

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SUBMODULE = join(ROOT, "contracts");
const SOURCE = join(SUBMODULE, "oracledesk-stellar");
const DEST = join(ROOT, "lib", "stellar", "generated");

import { FILES } from "./lib/files.mjs";

const check = process.argv.includes("--check");

if (!existsSync(SOURCE)) {
  console.error(
    `contracts submodule not found at ${relative(ROOT, SOURCE)}.\n` +
      "Run: git submodule update --init",
  );
  process.exit(2);
}

const commit = execFileSync("git", ["-C", SUBMODULE, "rev-parse", "HEAD"], {
  encoding: "utf8",
}).trim();

function render(src, contents) {
  if (src.endsWith(".json")) return contents;
  const header =
    `// AUTO-GENERATED by scripts/sync-bindings.mjs. DO NOT EDIT.\n` +
    `// Source: OracleDesk-SmartContract@${commit} oracledesk-stellar/${src}\n` +
    `// Regenerate with: npm run sync:bindings\n` +
    `// @ts-nocheck\n`;
  return header + contents;
}

let stale = 0;
mkdirSync(DEST, { recursive: true });

for (const [src, name] of FILES) {
  const from = join(SOURCE, src);
  const to = join(DEST, name);
  const expected = render(src, readFileSync(from, "utf8"));
  const current = existsSync(to) ? readFileSync(to, "utf8") : null;

  if (current === expected) {
    if (!check) console.log(`up to date  ${relative(ROOT, to)}`);
    continue;
  }
  if (check) {
    console.error(`stale       ${relative(ROOT, to)}  (from ${src})`);
    stale++;
    continue;
  }
  writeFileSync(to, expected);
  console.log(`wrote       ${relative(ROOT, to)}`);
}

// Binding provenance the running app can report (debug panel / diagnostics).
// Must match JSON.stringify(..., null, 2) + "\n" exactly so --check is stable.
{
  const to = join(DEST, "provenance.json");
  const expected =
    JSON.stringify(
      { contractsCommit: commit, files: Object.fromEntries(FILES.map(([src, name]) => [name, `oracledesk-stellar/${src}`])) },
      null,
      2,
    ) + "\n";
  const current = existsSync(to) ? readFileSync(to, "utf8") : null;
  if (current === expected) {
    if (!check) console.log(`up to date  ${relative(ROOT, to)}`);
  } else if (check) {
    console.error(`stale       ${relative(ROOT, to)}`);
    stale++;
  } else {
    writeFileSync(to, expected);
    console.log(`wrote       ${relative(ROOT, to)}`);
  }
}

// Capability spec bundle: base64 ScSpecEntry strings from each generated binding,
// used by scripts/capabilities-report.mjs and capability tests.
{
  const extractSpec = (filename) => {
    const text = readFileSync(join(DEST, filename), "utf8");
    const m = /new ContractSpec\(\[([\s\S]*?)\]\)/.exec(text);
    if (!m) return [];
    return [...m[1].matchAll(/"([^"]+)"/g)].map((x) => x[1]);
  };
  const capSpecs = {
    marketCore: extractSpec("market-core.ts"),
    treasury: extractSpec("treasury.ts"),
    resolver: extractSpec("resolver.ts"),
    reasoningRegistry: extractSpec("reasoning-registry.ts"),
  };
  const to = join(DEST, "capability-specs.json");
  const expected = JSON.stringify(capSpecs, null, 2) + "\n";
  const current = existsSync(to) ? readFileSync(to, "utf8") : null;
  if (current === expected) {
    if (!check) console.log(`up to date  ${relative(ROOT, to)}`);
  } else if (check) {
    console.error(`stale       ${relative(ROOT, to)}`);
    stale++;
  } else {
    writeFileSync(to, expected);
    console.log(`wrote       ${relative(ROOT, to)}`);
  }
}

// Pinned contract identity manifest for the app (lib/stellar/config.ts shows
// it before signing and flags builds that override canonical ids). Built from
// the submodule's deployments/testnet.json bytes, like the copied JSON above.
// Must match JSON.stringify(manifest, null, 2) exactly so --check is stable.
{
  const deploymentsRaw = readFileSync(join(SOURCE, "deployments", "testnet.json"));
  const deployments = JSON.parse(deploymentsRaw.toString("utf8"));
  const manifest = {
    network: "testnet",
    contractsCommit: commit,
    sha256: createHash("sha256").update(deploymentsRaw).digest("hex"),
    contracts: {
      marketCore: deployments.contracts.market_core,
      treasury: deployments.contracts.treasury,
      resolver: deployments.contracts.resolver,
      reasoningRegistry: deployments.contracts.reasoning_registry,
      usdc: deployments.contracts.usdc,
    },
    accounts: { deployer: deployments.deployer, agent: deployments.agent },
  };
  const expected =
    `// AUTO-GENERATED by scripts/sync-bindings.mjs. DO NOT EDIT.\n` +
    `// Source: OracleDesk-SmartContract@${commit} oracledesk-stellar/deployments/testnet.json\n` +
    `// Regenerate with: npm run sync:bindings\n` +
    `// @ts-nocheck\n` +
    `export const CONTRACT_MANIFEST = ` +
    JSON.stringify(manifest, null, 2) +
    ` as const;\n`;
  const to = join(DEST, "contract-manifest.ts");
  const current = existsSync(to) ? readFileSync(to, "utf8") : null;
  if (current === expected) {
    if (!check) console.log(`up to date  ${relative(ROOT, to)}`);
  } else if (check) {
    console.error(`stale       ${relative(ROOT, to)}`);
    stale++;
  } else {
    writeFileSync(to, expected);
    console.log(`wrote       ${relative(ROOT, to)}`);
  }
}

// Capability spec bundle: base64 ScSpecEntry strings from each generated binding,
// used by scripts/capabilities-report.mjs and capability tests.
{
  const extractSpec = (filename) => {
    const text = readFileSync(join(DEST, filename), "utf8");
    const m = /new ContractSpec\(\[([\s\S]*?)\]\)/.exec(text);
    if (!m) return [];
    return [...m[1].matchAll(/"([^"]+)"/g)].map((x) => x[1]);
  };
  const capSpecs = {
    marketCore: extractSpec("market-core.ts"),
    treasury: extractSpec("treasury.ts"),
    resolver: extractSpec("resolver.ts"),
    reasoningRegistry: extractSpec("reasoning-registry.ts"),
  };
  const to = join(DEST, "capability-specs.json");
  const expected = JSON.stringify(capSpecs, null, 2) + "\n";
  const current = existsSync(to) ? readFileSync(to, "utf8") : null;
  if (current === expected) {
    if (!check) console.log(`up to date  ${relative(ROOT, to)}`);
  } else if (check) {
    console.error(`stale       ${relative(ROOT, to)}`);
    stale++;
  } else {
    writeFileSync(to, expected);
    console.log(`wrote       ${relative(ROOT, to)}`);
  }
}

if (check) {
  if (stale > 0) {
    console.error(`\n${stale} generated file(s) are stale. Run: npm run sync:bindings`);
    process.exit(1);
  }
  console.log(`generated files match contracts@${commit.slice(0, 7)}`);
}
